This policy explains what information Reeta collects when you visit our website or place an order, why we collect it, and how you can reach us about it.

## What we collect
- Order details: your name, phone number, delivery address, the location you pin on the map, the items you order and any note you add.
- Messages: your name, phone or email and your message when you use the contact form.
- Browsing information: pages you visit, your device and browser type, and the link or campaign that brought you to the site.
- Your cart is saved in your own browser so it's still there when you come back. It is not sent to us until you place an order.

## Why we use it
- To prepare, confirm and deliver your order, and to contact you about it by phone or WhatsApp.
- To calculate your delivery fee from the distance to your address.
- To answer your messages and help with any problem.
- To keep the store safe, for example by limiting repeated or fake orders.
- To understand how people use the site and which campaigns work, so we can improve it.

## Advertising and analytics
We may use tools such as Meta Pixel, TikTok Pixel and Google Analytics to measure visits and purchases and to show our ads to people who may like our products. These tools may use cookies or similar technology. You can limit this from your browser settings and from the ad settings of each platform.

## Who we share it with
- The courier who delivers your order receives your name, phone number and address.
- Trusted services that run our website, database and email store the data on our behalf.
- We never sell your information.

## Payments
We don't collect card details. Cash is paid on delivery, and InstaPay transfers happen inside your own banking app.

## How long we keep it
We keep order records for as long as we need them for delivery, customer service and our accounts. You can ask us to delete your information at any time, unless we must keep it by law.

## Your choices
You can ask to see, correct or delete the information we hold about you. Message us on WhatsApp or email reetadeserts@gmail.com and we'll take care of it.

